"""
Enterprise Rare Blood Type Availability Analytics
Pipeline Stage 9 — Inventory Transaction Engine (v2 upgrade)
=====================================================

This is the core of the project upgrade: it replaces "trust the static
snapshot" with "recompute current inventory from the transaction ledger",
per the reconciliation equation:

    Current Inventory
        =
    Opening Inventory (0)
        + DONATION
        + TRANSFER_IN
        - ISSUE
        - TRANSFER_OUT
        - EXPIRY
        + ADJUSTMENT

It reads the transaction ledger generated by
data_generation/02_generate_transactional_data.py (itself tied to real
donation history -- see that script's docstring), and produces:

    gold/gold_inventory_state          component-level current state,
                                        coverage days, shortage score,
                                        priority level, recommended action
    gold/gold_demand_analytics         daily/average demand per
                                        bank+blood_group+component
    gold/gold_transfer_history         cleaned, validated transfer ledger

All business-rule values (component types, shelf life, scoring weights,
priority bands, recommended actions) are loaded from config/*.yaml -- this
script contains NO hard-coded copies of those numbers.
"""

