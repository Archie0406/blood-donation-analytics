# MAIN
# ============================================================================

def main() -> None:
    print("=" * 45)
    print("INVENTORY TRANSACTION ENGINE (v2 upgrade)")
    print("=" * 45)

    spark = create_spark_session()

    try:
        print("\nReading transaction ledger...")
        transactions = read_transactions(spark)
        txn_count = transactions.count()
        print(f"Transactions loaded: {txn_count}")

        if txn_count == 0:
            print("ERROR: transaction ledger is empty. "
                  "Run data_generation/02_generate_transactional_data.py first.")
            sys.exit(1)

        print("\nStep 1: Recomputing current inventory balances from the ledger...")
        balances = compute_inventory_balances(transactions)
        balances = compute_expiry_status(balances)

        print("Step 2: Computing demand analytics...")
        demand = compute_demand_analytics(transactions)

        print("Step 3: Computing coverage days...")
        inventory = add_coverage_days(balances, demand)

        print("Step 4: Computing donation trend sub-score...")
        inventory = add_donation_trend_sub_score(inventory, transactions)

        print("Step 5: Computing shortage score + priority level...")
        inventory = add_shortage_score(inventory)
        inventory = add_priority_level(inventory)

        blood_bank_ids = {
            r["blood_bank_id"] for r in inventory.select("blood_bank_id").distinct().collect()
        }
        print("\nReading and validating blood transfers...")
        transfers = read_and_validate_transfers(spark, blood_bank_ids)
        invalid_transfers = transfers.filter(~F.col("is_valid")).count() if transfers.count() > 0 else 0
        print(f"Transfer records: {transfers.count()} ({invalid_transfers} flagged invalid)")

        reconciliation_ok = run_reconciliation_check(transactions, inventory)

        gold_inventory_state = inventory.select(
            "blood_bank_id", "blood_group", "component_type", "available_units",
            "expiry_status", "lifetime_expired_units", "has_demand_data",
            "average_daily_demand", "average_weekly_demand", "average_monthly_demand",
            "coverage_days", "inventory_level_sub_score", "coverage_sub_score",
            "expiry_sub_score", "donation_trend_sub_score", "shortage_score",
            "priority_level", "recommended_action", "last_updated",
        )

        gold_demand_analytics = demand.select(
            "blood_bank_id", "blood_group", "component_type", "total_units_issued",
            "issue_event_count", "observation_window_days", "average_daily_demand",
            "average_weekly_demand", "average_monthly_demand",
        )

        print("\nWriting Gold datasets...")
        write_gold(gold_inventory_state, GOLD_INVENTORY_STATE, "gold_inventory_state")
        write_gold(gold_demand_analytics, GOLD_DEMAND_ANALYTICS, "gold_demand_analytics")
        write_gold(transfers, GOLD_TRANSFER_HISTORY, "gold_transfer_history")

        print("\n" + "=" * 45)
        print("SUMMARY")
        print("=" * 45)
        priority_counts = gold_inventory_state.groupBy("priority_level").count().collect()
        for row in sorted(priority_counts, key=lambda r: r["priority_level"]):
            print(f"  {row['priority_level']:<10}: {row['count']}")

        rare_state = gold_inventory_state.filter(F.col("blood_group").isin(RARE_BLOOD_GROUPS))
        print(f"\nRare blood group ledgers: {rare_state.count()}")
        print(f"Rare blood EMERGENCY/CRITICAL count: "
              f"{rare_state.filter(F.col('priority_level').isin('EMERGENCY', 'CRITICAL')).count()}")

        print("\n" + "=" * 45)
        if reconciliation_ok:
            print("INVENTORY TRANSACTION ENGINE COMPLETE — RECONCILIATION PASSED")
        else:
            print("INVENTORY TRANSACTION ENGINE COMPLETE — RECONCILIATION FAILED")
        print("=" * 45)

        if not reconciliation_ok:
            sys.exit(1)

    except FileNotFoundError as exc:
        print(f"\nERROR: {exc}")
        sys.exit(1)

    finally:
        spark.stop()


if __name__ == "__main__":
    main()
